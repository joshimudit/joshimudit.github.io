// Regenerates src/lib/range/curve.ts: how the stay-village and the move-village end up after
// 50 years, for 11 settings of the "how unpredictable is the rain" dial, averaged over 60 rain histories.
//   node_modules/.bin/esbuild scripts/range-curve.ts --bundle --platform=node --format=esm --outfile=/tmp/curve.mjs && node /tmp/curve.mjs > src/lib/range/curve.ts
import { run, rainSeries, climate, tally, totals } from "../src/lib/range/model.ts";
const SEEDS = 60, YEARS = 50;
const rows: string[] = [];
for (let k = 0; k <= 10; k++) {
  const u = k / 10, c = climate(u);
  let sH = 0, mH = 0, sA = 0, mA = 0, sY = 0, tot = 0, mWins = 0;
  for (let seed = 1; seed <= SEEDS; seed++) {
    const rain = rainSeries(YEARS, c.cv, seed, 0.2);
    const a = run({ seed, strategies: "stay" }, rain, c.storms), b = run({ seed, strategies: "move" }, rain, c.storms);
    const ta = tally(a), tb = tally(b);
    sH += ta.herding; mH += tb.herding; sA += ta.animals; mA += tb.animals;
    if (tb.herding > ta.herding) mWins++;
    const A = totals(a), B = totals(b);
    for (let t = 1; t < A.length; t++) if (A[t - 1] > 0 && B[t - 1] > 0) { tot++; if (A[t] / A[t - 1] > B[t] / B[t - 1]) sY++; }
  }
  const f = (x: number, d = 1) => (x / SEEDS).toFixed(d);
  rows.push(`  { u: ${u}, cv: ${c.cv.toFixed(3)}, stayFamilies: ${f(sH)}, moveFamilies: ${f(mH)}, stayAnimals: ${f(sA, 0)}, moveAnimals: ${f(mA, 0)}, stayBetterYears: ${(sY / tot).toFixed(2)}, moveWins: ${(mWins / SEEDS).toFixed(2)} },`);
}
console.log(`// Generated by scripts/range-curve.ts — do not edit by hand.
// Two villages of 15 families after ${YEARS} years, averaged over ${SEEDS} rain histories per setting.
export const CURVE = [
${rows.join("\n")}
];`);
